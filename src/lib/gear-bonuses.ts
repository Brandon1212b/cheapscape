/** Returns the primary offensive bonus for efficiency sorting, or 0 if unknown / none. */
export function offensiveBonus(name: string): number {
  return OFFENSIVE_BONUS[name] ?? 0;
}

/**
 * Cost per unit of offensive bonus. Lower is better value.
 * Items with no bonus sort to the end (Infinity).
 */
export function costPerBonus(price: number, bonus: number): number {
  if (bonus <= 0 || price <= 0) return Number.POSITIVE_INFINITY;
  return price / bonus;
}
